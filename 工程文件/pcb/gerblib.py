class Excellon:
    def __init__(self):
        self.tools = {}   # T num -> diameter
        self.hits = []    # (tool, x, y)

    def add(self, d, x, y):
        t = None
        for k, v in self.tools.items():
            if abs(v - d) < 1e-6:
                t = k
                break
        if t is None:
            t = len(self.tools) + 1
            self.tools[t] = d
        self.hits.append((t, x, y))

    def save(self, path, plated=True):
        lines = ['M48', ';TYPE=PLATED' if plated else ';TYPE=NONPLATED',
                 'METRIC,TZ']
        for t, d in sorted(self.tools.items()):
            lines.append('T%dC%.3f' % (t, d))
        lines.append('%')
        lines.append('G90')
        lines.append('G05')
        for t, d in sorted(self.tools.items()):
            hits = [(x, y) for (tt, x, y) in self.hits if tt == t]
            if not hits: continue
            lines.append('T%d' % t)
            for (x, y) in hits:
                lines.append('X%.3fY%.3f' % (x, y))
        lines.append('T0')
        lines.append('M30')
        with open(path, 'w') as f:
            f.write('\n'.join(lines) + '\n')
