CHAR_W = 0.75     # 字宽（含间隙）相对字高


def text_strokes(s, x, y, h, rot=0.0):
    """返回字符串的线段列表 [(x1,y1,x2,y2),...]，(x,y)=首字左上角，h=字高 mm。"""
    segs = []
    adv = h * CHAR_W
    for ch in s:
        g = FONT.get(ch.upper(), FONT.get(' ', []))
        for (x1, y1), (x2, y2) in g:
            px1, py1 = x + x1 * h, y + y1 * h
            px2, py2 = x + x2 * h, y + y2 * h
            if rot:
                cx, cy = x + 0.3 * h, y + 0.5 * h
                for (pxi, pyi) in ((px1, py1), (px2, py2)):
                    pass
                # 绕 (cx,cy) 旋转
                def rp(px, py):
                    dx, dy = px - cx, py - cy
                    a = math.radians(rot)
                    return (cx + dx * math.cos(a) - dy * math.sin(a),
                            cy + dx * math.sin(a) + dy * math.cos(a))
                px1, py1 = rp(px1, py1)
                px2, py2 = rp(px2, py2)
            segs.append((px1, py1, px2, py2))
        x += adv
    return segs


