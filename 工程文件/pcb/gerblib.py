class Gerber:
    """简单 Gerber 写出器：圆形/矩形闪光 + 圆头走线 + 多边形区域 + 明暗极性。"""

    def __init__(self):
        self.ops = []          # 原始操作列表
        self.apertures = {}    # name -> (type, params)
        self._cur = None
        self._polarity = 'D'
        self._npoly = 0

    # ---- 内部 ----
    def _emit(self, s):
        self.ops.append(s)

    def _fmt(self, v):
        return ('%.6f' % v).rstrip('0').rstrip('.') if v != 0 else '0'

    def _xy(self, x, y):
        return 'X%sY%s' % (self._fmt(round(x, 5)), self._fmt(round(y, 5)))

    def _ap(self, name, typ, params):
        if name not in self.apertures:
            self.apertures[name] = (typ, params)
            self._emit('%%ADD%s%s,%s*%%' % (name, typ, params))
        return name

    def circle(self, d):
        return self._ap('C%s' % ('%.4f' % d).rstrip('0').rstrip('.'), 'C', '%.4f' % d)

    def rect(self, w, h):
        n = 'R%sx%s' % ('%.3f' % w, '%.3f' % h)
        return self._ap(n, 'R', '%.3f,%.3f' % (w, h))

    def select(self, name):
        if name != self._cur:
            self._emit('D%s*' % name)
            self._cur = name

    # ---- 图元 ----
    def polarity(self, p):
        if p != self._polarity:
            self._emit('%%LP%s*%%' % p)
            self._polarity = p

    def flash(self, x, y, ap):
        self.select(ap)
        self._emit('X%sY%sD03*' % (self._fmt(round(x, 5)), self._fmt(round(y, 5))))

    def draw(self, pts, width):
        ap = self.circle(width)
        self.select(ap)
        prev = None
        for (x, y) in pts:
            if prev is not None:
                self._emit('X%sY%sD01*' % (self._fmt(round(x, 5)), self._fmt(round(y, 5))))
            else:
                self._emit('X%sY%sD02*' % (self._fmt(round(x, 5)), self._fmt(round(y, 5))))
            prev = (x, y)

    def region(self, pts):
        """多边形区域（自动闭合）。"""
        self._emit('G36*')
        prev = None
        for (x, y) in pts:
            if prev is None:
                self._emit('X%sY%sD02*' % (self._fmt(round(x, 5)), self._fmt(round(y, 5))))
            else:
                self._emit('X%sY%sD01*' % (self._fmt(round(x, 5)), self._fmt(round(y, 5))))
            prev = (x, y)
        self._emit('D01*')   # 闭合回起点
        self._emit('G37*')

    # ---- 输出 ----
    def save(self, path, attrs):
        hdr = ['G04 IPQ-2026 carrier board*',
               '%FSLAX35Y35*%',
               '%MOMM*%']
        for k, v in attrs.items():
            if v is None: continue
            hdr.append('%%TF.%s,%s*%%' % (k, v))
        body = hdr + self.ops + ['M02*']
        with open(path, 'w') as f:
            f.write('\n'.join(body) + '\n')


